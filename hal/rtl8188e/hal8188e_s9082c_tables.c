int s9082c_mac_config(PADAPTER Adapter)
{
	int i;

	RTW_INFO("%s: Configuring SmartChip S9082C MAC...\n", __FUNCTION__);

	for (i = 0; i < (int)(sizeof(s9082c_mac_init_seq) / sizeof(s9082c_mac_init_seq[0])); i++) {
		rtw_write32(Adapter, s9082c_mac_init_seq[i].reg, s9082c_mac_init_seq[i].val);
		rtw_udelay_os(1);
	}

	rtw_write16(Adapter, 0x44ca, 0xe0e0);

	RTW_INFO("%s: S9082C MAC configured successfully.\n", __FUNCTION__);
	return _SUCCESS;
}

int s9082c_bb_config(PADAPTER Adapter)
{
	HAL_DATA_TYPE *pHalData = GET_HAL_DATA(Adapter);
	u16 regval;
	u32 cap;
	int i;

	RTW_INFO("%s: Configuring SmartChip S9082C Baseband and AGC...\n", __FUNCTION__);

	/* 1. Register definitions for S9082 RF */
	pHalData->PHYRegDef[RF_PATH_A].rfintfs = 0x4870;
	pHalData->PHYRegDef[RF_PATH_A].rfintfo = 0x4860;
	pHalData->PHYRegDef[RF_PATH_A].rfintfe = 0x4860;
	pHalData->PHYRegDef[RF_PATH_A].rf3wireOffset = 0x4840;
	pHalData->PHYRegDef[RF_PATH_A].rfHSSIPara2 = 0x4824;
	pHalData->PHYRegDef[RF_PATH_A].rfLSSIReadBack = 0x48a0;
	pHalData->PHYRegDef[RF_PATH_A].rfLSSIReadBackPi = 0x48b8;

	/* 2. Clock & Functional Enable from 9082xs_obj.o ConfigPHY_BB9083X */
	regval = rtw_read16(Adapter, 0x4002);
	rtw_write16(Adapter, 0x4002, regval | 0x4c0);
	rtw_write8(Adapter, 0x401f, 0xe0);
	rtw_write8(Adapter, 0x4002, 0xc7);

		/* 3. Execute TDB_S9082_Init_PHY (284 register writes) */
	for (i = 0; i < (int)(sizeof(s9082c_phy_init_seq) / sizeof(s9082c_phy_init_seq[0])); i++) {
		u16 reg = s9082c_phy_init_seq[i].reg;
		u32 mask = s9082c_phy_init_seq[i].mask;
		u32 val = s9082c_phy_init_seq[i].val;
		u8 op = s9082c_phy_init_seq[i].op;

		if (op == OP_DIRECT) {
			rtw_write32(Adapter, reg, val);
		} else if (op == OP_BB_ND) {
			u32 orig = rtw_read32(Adapter, reg);
			u32 shift = PHY_CalculateBitShift(mask);
			u32 data = ((orig & (~mask)) | ((val << shift) & mask));
			rtw_write32(Adapter, reg, data);
		} else {
			s9082c_write_bbreg(Adapter, reg, mask, val);
		}
		rtw_udelay_os(1);
	}

	/* 4. Execute TDB_S9082_Init_AGC (130 register writes) */
	for (i = 0; i < (int)(sizeof(s9082c_agc_init_seq) / sizeof(s9082c_agc_init_seq[0])); i++) {
		rtw_write32(Adapter, s9082c_agc_init_seq[i].reg, s9082c_agc_init_seq[i].val);
		rtw_udelay_os(1);
	}

	/* 5. Set crystal cap on reg 0x4024 mask 0x7ff800 (AlexELEC CrystalCap_ProSet_Hal @ 0x8252c) */
	cap = pHalData->crystal_cap & 0x3f;
	cap |= (cap << 6);
	s9082c_write_bbreg(Adapter, 0x4024, 0x7ff800, cap);

	/* 6. Configure RF Path Switch (Main Antenna) */
	s9082c_set_rf_path_switch(Adapter, _TRUE);

	RTW_INFO("%s: S9082C Baseband and AGC configured successfully (crystal_cap=0x%02x, val=0x%03x).\n",
		 __FUNCTION__, pHalData->crystal_cap, cap);
	return _SUCCESS;
}


/* --- SmartChip S9082C BB / RF / Channel Bit-Reversal Operations --- */

/* s9082_bit_reverse32 moved to hal8188e_s9082c_tables.h */

/* 12 BB registers proven non-reversed (_nd) in 9082xs_obj.o */
static inline bool s9082c_is_nd_bbreg(u32 RegAddr)
{
	u32 off = (RegAddr >= 0x4000) ? (RegAddr - 0x4000) : RegAddr;
	switch (off) {
	case 0x824:
	case 0x82c:
	case 0xa20:
	case 0xa24:
	case 0xa28:
	case 0xc4c:
	case 0xc50:
	case 0xc58:
	case 0xc80:
	case 0xc88:
	case 0xc94:
	case 0xe00:
		return _TRUE;
	default:
		return _FALSE;
	}
}

u32 s9082c_read_bbreg(PADAPTER Adapter, u32 RegAddr, u32 BitMask)
{
	u32 OriginalValue, BitShift;

	OriginalValue = rtw_read32(Adapter, RegAddr);
	if (!s9082c_is_nd_bbreg(RegAddr))
		OriginalValue = s9082_bit_reverse32(OriginalValue);

	if (BitMask != 0xffffffff) {
		BitShift = PHY_CalculateBitShift(BitMask);
		OriginalValue = (OriginalValue & BitMask) >> BitShift;
	}

	return OriginalValue;
}

void s9082c_write_bbreg(PADAPTER Adapter, u32 RegAddr, u32 BitMask, u32 Data)
{
	u32 OriginalValue, BitShift;
	bool is_nd = s9082c_is_nd_bbreg(RegAddr);

	if (BitMask != 0xffffffff) {
		OriginalValue = rtw_read32(Adapter, RegAddr);
		if (!is_nd)
			OriginalValue = s9082_bit_reverse32(OriginalValue);
		BitShift = PHY_CalculateBitShift(BitMask);
		Data = ((OriginalValue & (~BitMask)) | ((Data << BitShift) & BitMask));
	}

	if (!is_nd)
		Data = s9082_bit_reverse32(Data);
	rtw_write32(Adapter, RegAddr, Data);
}

u32 s9082c_read_rfreg(PADAPTER Adapter, enum rf_path eRFPath, u32 RegAddr, u32 BitMask)
{
	u32 retValue = 0, tmplong, tmplong2, BitShift;
	HAL_DATA_TYPE *pHalData = GET_HAL_DATA(Adapter);
	BB_REGISTER_DEFINITION_T *pPhyReg = &pHalData->PHYRegDef[eRFPath];
	u8 RfPiEnable = 0;

	RegAddr &= 0xff;
	tmplong = rtw_read32(Adapter, 0x4824);
	tmplong2 = (tmplong & 0x807fffff) | (RegAddr << 23) | 0x80000000;

	rtw_write32(Adapter, 0x4824, tmplong & 0x7fffffff);
	rtw_udelay_os(10);
	rtw_write32(Adapter, pPhyReg->rfHSSIPara2, tmplong2);
	rtw_udelay_os(100);
	rtw_udelay_os(10);

	RfPiEnable = (u8)s9082c_read_bbreg(Adapter, 0x4820, 0x100);
	if (RfPiEnable)
		retValue = s9082c_read_bbreg(Adapter, pPhyReg->rfLSSIReadBackPi, 0xfffff);
	else
		retValue = s9082c_read_bbreg(Adapter, pPhyReg->rfLSSIReadBack, 0xfffff);

	if (BitMask != 0xfffff) {
		BitShift = PHY_CalculateBitShift(BitMask);
		retValue = (retValue & BitMask) >> BitShift;
	}

	return retValue;
}

void s9082c_write_rfreg(PADAPTER Adapter, enum rf_path eRFPath, u32 RegAddr, u32 BitMask, u32 Data)
{
	u32 Original_Value, BitShift, DataAndAddr;
	HAL_DATA_TYPE *pHalData = GET_HAL_DATA(Adapter);
	BB_REGISTER_DEFINITION_T *pPhyReg = &pHalData->PHYRegDef[eRFPath];

	RegAddr &= 0xff;
	if (BitMask != 0xfffff) {
		Original_Value = s9082c_read_rfreg(Adapter, eRFPath, RegAddr, 0xfffff);
		BitShift = PHY_CalculateBitShift(BitMask);
		Data = ((Original_Value & (~BitMask)) | ((Data << BitShift) & BitMask));
	}

	DataAndAddr = ((RegAddr << 20) | (Data & 0xfffff));
	s9082c_write_bbreg(Adapter, pPhyReg->rf3wireOffset, 0xffffffff, DataAndAddr);
}

void s9082c_set_chnl_bw(PADAPTER Adapter, u8 channel, enum channel_width Bandwidth, u8 Offset40, u8 Offset80)
{
	HAL_DATA_TYPE *pHalData = GET_HAL_DATA(Adapter);
	u8 regBwOpMode;
	u32 val;

	if (channel == 0)
		channel = 1;

	pHalData->current_channel = channel;
	pHalData->current_channel_bw = Bandwidth;
	pHalData->nCur40MhzPrimeSC = Offset40;

	rtw_hal_set_tx_power_level(Adapter, channel);

	/* Guard: Ensure upper synthesizer PLL bits [19:12] remain preserved.
	 * S9082C-FIX: Bit 15 (0x8000) is the LCK (LC-tank/VCO) calibration trigger.
	 * It must be 0 in channel-set writes — the init triggers the LCK once with a
	 * 100ms delay; re-setting it here (every channel change) re-triggers the VCO
	 * calibration mid-lock. Mask it off. */
	if ((pHalData->RfRegChnlVal[RF_PATH_A] & 0x07000) == 0)
		pHalData->RfRegChnlVal[RF_PATH_A] |= 0x07400;
	pHalData->RfRegChnlVal[RF_PATH_A] &= ~0x8000;

	/* 1. tilk_SwChnl9083X: Update channel first */
	val = (pHalData->RfRegChnlVal[RF_PATH_A] & 0xfffffc00) | (channel & 0x3ff);
	pHalData->RfRegChnlVal[RF_PATH_A] = val;
	s9082c_write_rfreg(Adapter, RF_PATH_A, 0x18, 0xfffff, val);

	/* 2. tilk_SetBWMode9083X: Update MAC & Baseband BW registers */
	regBwOpMode = rtw_read8(Adapter, 0x4603);
	if (Bandwidth == CHANNEL_WIDTH_20) {
		rtw_write8(Adapter, 0x4603, regBwOpMode | 0x20);
		s9082c_write_bbreg(Adapter, 0x4800, 0x01, 0x00);
		s9082c_write_bbreg(Adapter, 0x4900, 0x01, 0x00);
	} else {
		rtw_write8(Adapter, 0x4603, regBwOpMode & ~0x20);
		rtw_write8(Adapter, 0x4442, (rtw_read8(Adapter, 0x4442) & 0x09) | s9082_bit_reverse8((Offset40 << 5) & 0xe0));
		s9082c_write_bbreg(Adapter, 0x4800, 0x01, 0x01);
		s9082c_write_bbreg(Adapter, 0x4900, 0x01, 0x01);
		s9082c_write_bbreg(Adapter, 0x4a00, 0x10, (Offset40 >> 1) & 0x01);
		s9082c_write_bbreg(Adapter, 0x4d00, 0xc00, Offset40 & 0x03);
		s9082c_write_bbreg(Adapter, 0x4818, 0xc000000, (Offset40 == 1) ? 2 : 1);
	}

	/* 3. _PHY_RF8353SetBandwidth_tll9083x: Update bandwidth in RF 0x18 */
	if (Bandwidth == CHANNEL_WIDTH_20) {
		val = pHalData->RfRegChnlVal[RF_PATH_A] | 0x0c00;
	} else {
		val = (pHalData->RfRegChnlVal[RF_PATH_A] & 0xfffff3ff) | 0x0400;
	}
	pHalData->RfRegChnlVal[RF_PATH_A] = val;
	s9082c_write_rfreg(Adapter, RF_PATH_A, 0x18, 0xfffff, val);

	/* S9082C-DIAG: echter RF-Readback (0x4824-Pfad, NICHT 0x4840!) — optional
	 * (rtw_s9082_rf_readback). Zeigt, ob der RF8353 den Kanal annimmt; NICHT passiv. */
	if (rtw_s9082_rf_readback) {
		u32 rf18_rb = s9082c_read_rfreg(Adapter, RF_PATH_A, 0x18, 0xfffff);
		RTW_INFO("S9RF18: ch=%u req=0x%05x rb=0x%05x\n", channel, val, rf18_rb);
	}

	/* 4. Spur calibration (tilk_SpurCalibration_9083X @ 0x6ad34) */
	if (channel == 13 || channel == 14 || (Bandwidth == CHANNEL_WIDTH_40 && channel == 11)) {
		s9082c_write_bbreg(Adapter, 0x4c40, 0x200, 1);
		s9082c_write_bbreg(Adapter, 0x4d3c, 0x1c0, 2);
	} else {
		s9082c_write_bbreg(Adapter, 0x4c40, 0x200, 0);
	}

	/* Ensure packet reception filters remain active */
	rtw_write16(Adapter, 0x46a4, 0xffff);

	RTW_INFO("s9082c_set_chnl_bw: ch=%u bw=%u rf18=0x%05x\n", channel, Bandwidth, val);
}

void s9082c_set_rf_path_switch(PADAPTER Adapter, bool is_main)
{
	u8 ledcfg2;

	/* 0x404e BIT0: LED/Antenna switch control (PHY_RF_Path_Switch_Set @ 0x7f230 in 9082xs_obj.o) */
	ledcfg2 = rtw_read8(Adapter, 0x404e);
	rtw_write8(Adapter, 0x404e, ledcfg2 | 0x01);

	/* 0x4878 BIT13 (0x2000): FPGA0_XAB_RF_PARAMETER */
	s9082c_write_bbreg(Adapter, 0x4878, 0x2000, 1);

	/* 0x4870 BIT[9:8] (0x300): FPGA0_XAB_RF_INTERFACE_SW = 0 */
	s9082c_write_bbreg(Adapter, 0x4870, 0x300, 0);

	/* 0x4914 = 0x4080 (antenna mapping table, 16-bit direct write) */
	rtw_write16(Adapter, 0x4914, 0x4080);

	/* 0x4860 BIT[14:12] (0x7000): Tx antenna switch */
	s9082c_write_bbreg(Adapter, 0x4860, 0x7000, is_main ? 1 : 0);

	/* 0x4864 BIT[5:3] (0x38): Rx antenna switch */
	s9082c_write_bbreg(Adapter, 0x4864, 0x38, is_main ? 1 : 0);

	RTW_INFO("S9082C RF Path Switch set to %s (0x404e=0x%02x)\n",
		 is_main ? "MAIN" : "AUX", ledcfg2 | 0x01);
}

void s9082c_set_bcn_related_regs(PADAPTER padapter)
{
	struct mlme_ext_priv *pmlmeext = &(padapter->mlmeextpriv);
	struct mlme_ext_info *pmlmeinfo = &(pmlmeext->mlmext_info);
	u16 bcn_int = pmlmeinfo->bcn_interval;
	u16 bcn_int_rev;
	u32 val32;

	rtw_write16(padapter, 0x455a, 0x0040); /* REG_BCN_MAX_ERR */

	bcn_int_rev = (s9082_bit_reverse8(bcn_int & 0xff)) | ((u16)s9082_bit_reverse8((bcn_int >> 8) & 0xff) << 8);
	rtw_write16(padapter, 0x4554, bcn_int_rev); /* REG_BCN_INTERVAL */

	InitBeaconParameters_8188e(padapter);

	rtw_write8(padapter, 0x451b, 0x90);

	val32 = rtw_read32(padapter, 0x4604);
	rtw_write32(padapter, 0x4604, val32 & ~0x80);
	rtw_write32(padapter, 0x4604, val32 | 0x80);

	if (pmlmeext->cur_wireless_mode & (WIRELESS_11A | WIRELESS_11_24N))
		rtw_write16(padapter, 0x455e, 0x0a0a);

	rtw_write8(padapter, 0x4550, 0x58);
	rtw_write8(padapter, 0x4525, 0xf6);
	ResumeTxBeacon(padapter);
	rtw_write8(padapter, 0x4550, rtw_read8(padapter, 0x4550) | 0x40);
}

void s9082c_lc_calibrate(PADAPTER Adapter)
{
	HAL_DATA_TYPE *pHalData = GET_HAL_DATA(Adapter);
	u8 tmpreg;
	u32 rf_amode = 0, lc_cal;

	tmpreg = rtw_read8(Adapter, 0x4d03);
	if ((tmpreg & 0x0e) != 0)
		rtw_write8(Adapter, 0x4d03, tmpreg & ~0x0e);
	else
		rtw_write8(Adapter, 0x4522, 0xff);

	if ((tmpreg & 0x0e) != 0) {
		rf_amode = s9082c_read_rfreg(Adapter, RF_PATH_A, 0x00, 0xfffff);
		s9082c_write_rfreg(Adapter, RF_PATH_A, 0x00, 0xfffff,
				   (rf_amode & 0x8ffff) | 0x10000);
	}

	lc_cal = s9082c_read_rfreg(Adapter, RF_PATH_A, 0x18, 0xfffff);
	s9082c_write_rfreg(Adapter, RF_PATH_A, 0x18, 0xfffff, lc_cal | 0x8000);

	rtw_msleep_os(100);

	if ((tmpreg & 0x0e) != 0) {
		rtw_write8(Adapter, 0x4d03, tmpreg);
		s9082c_write_rfreg(Adapter, RF_PATH_A, 0x00, 0xfffff, rf_amode);
	} else {
		rtw_write8(Adapter, 0x4522, 0x00);
	}

	/* Restore clean RF 0x18 word */
	s9082c_write_rfreg(Adapter, RF_PATH_A, 0x18, 0xfffff, lc_cal);

	RTW_INFO("S9082C LCK done (tmpreg=0x%02x, lc_cal=0x%05x restored=0x%05x)\n",
		 tmpreg, lc_cal, lc_cal);
}

static u8 s9082c_path_a_tx_iqk(PADAPTER Adapter)
{
	u32 eac, e94, e9c;

	rtw_write32(Adapter, 0x4e30, 0x08003138);
	rtw_write32(Adapter, 0x4e34, 0x0c003138);
	rtw_write32(Adapter, 0x4e38, 0x4128c054);
	rtw_write32(Adapter, 0x4e3c, 0x14680000);
	rtw_write32(Adapter, 0x4e4c, 0x00629488);
	rtw_write32(Adapter, 0x4e48, 0x9f000000);
	rtw_write32(Adapter, 0x4e48, 0x1f000000);
	rtw_mdelay_os(10);

	eac = rtw_read32(Adapter, 0x4eac);
	e94 = rtw_read32(Adapter, 0x4e94);
	e9c = s9082c_read_bbreg(Adapter, 0x4e9c, 0xffffffff);

	if (!(eac & BIT(28)) &&
	    (((e94 >> 16) & 0x3ff) != 0x142) &&
	    (((e9c >> 16) & 0x3ff) != 0x42))
		return 0x01;

	return 0x00;
}

static u8 s9082c_path_a_rx_iqk(PADAPTER Adapter)
{
	u32 eac, e94, e9c, ea4, u4tmp;

	/* Stage 1: TX-side prep for RX IQK */
	s9082c_write_bbreg(Adapter, 0x4e28, 0xffffff00, 0);
	rtw_write32(Adapter, 0x4840, 0x701f0005);
	rtw_write32(Adapter, 0x4840, 0xc0c00000);
	rtw_write32(Adapter, 0x4840, 0xc00800f0);
	rtw_write32(Adapter, 0x4840, 0xc0f488de);
	s9082c_write_bbreg(Adapter, 0x4e28, 0xffffff00, 0x00808000);
	rtw_write32(Adapter, 0x4e40, 0x80003e00);
	rtw_write32(Adapter, 0x4e44, 0x81001200);
	rtw_write32(Adapter, 0x4e30, 0x08003138);
	rtw_write32(Adapter, 0x4e34, 0x0c003138);
	rtw_write32(Adapter, 0x4e38, 0x41681020);
	rtw_write32(Adapter, 0x4e3c, 0x14680000);
	rtw_write32(Adapter, 0x4e4c, 0x00629588);
	rtw_write32(Adapter, 0x4e48, 0x9f000000);
	rtw_write32(Adapter, 0x4e48, 0x1f000000);
	rtw_mdelay_os(10);

	eac = rtw_read32(Adapter, 0x4eac);
	e94 = rtw_read32(Adapter, 0x4e94);
	e9c = s9082c_read_bbreg(Adapter, 0x4e9c, 0xffffffff);

	if ((eac & BIT(28)) ||
	    (((e94 >> 16) & 0x3ff) == 0x142) ||
	    (((e9c >> 16) & 0x3ff) == 0x42))
		return 0x00;

	/* Stage 2: RX IQK */
	u4tmp = 0x80007c00 | (e94 & 0x3ff0000) | ((e9c >> 16) & 0x3ff);
	s9082c_write_bbreg(Adapter, 0x4e40, 0xffffffff, u4tmp);
	rtw_write32(Adapter, 0x4e28, 0x00000000);
	rtw_write32(Adapter, 0x4840, 0x701f0005);
	rtw_write32(Adapter, 0x4840, 0xc0c00000);
	rtw_write32(Adapter, 0x4840, 0xc00800f0);
	rtw_write32(Adapter, 0x4840, 0xc0f4fe5f);
	s9082c_write_bbreg(Adapter, 0x4e28, 0xffffff00, 0x00808000);
	rtw_write32(Adapter, 0x4e44, 0x80001200);
	rtw_write32(Adapter, 0x4e30, 0x0c003138);
	rtw_write32(Adapter, 0x4e34, 0x08003138);
	rtw_write32(Adapter, 0x4e38, 0x416830a0);
	rtw_write32(Adapter, 0x4e3c, 0x146830a0);
	rtw_write32(Adapter, 0x4e4c, 0x00629588);
	rtw_write32(Adapter, 0x4e48, 0x9f000000);
	rtw_write32(Adapter, 0x4e48, 0x1f000000);
	rtw_mdelay_os(10);

	eac = rtw_read32(Adapter, 0x4eac);
	ea4 = rtw_read32(Adapter, 0x4ea4);

	if (!(eac & BIT(27)) &&
	    (((ea4 >> 16) & 0x3ff) != 0x132) &&
	    (((eac >> 16) & 0x3ff) != 0x36))
		return 0x03;

	return 0x01;
}

static void s9082c_iqk_single(PADAPTER Adapter, s32 result[][8], u8 t,
			      u32 *adda_backup, u32 *iqk_bb_backup,
			      u8 *raw_4522, u8 *raw_4550, u8 *raw_4551,
			      u32 *raw_4040, u8 *pi_mode)
{
	static const u32 adda_regs[16] = {
		0x485c, 0x4e6c, 0x4e70, 0x4e74, 0x4e78, 0x4e7c, 0x4e80, 0x4e84,
		0x4e88, 0x4e8c, 0x4ed0, 0x4ed4, 0x4ed8, 0x4edc, 0x4ee0, 0x4eec
	};
	static const u32 iqk_bb_regs[9] = {
		0x4c04, 0x4c08, 0x4874, 0x4b68, 0x4b6c, 0x4870, 0x4860, 0x4864, 0x4a04
	};
	u32 i;
	u8 retry = 2, patha_ok;

	if (t == 0) {
		for (i = 0; i < 16; i++)
			adda_backup[i] = rtw_read32(Adapter, adda_regs[i]);
		*raw_4522 = rtw_read8(Adapter, 0x4522);
		*raw_4550 = rtw_read8(Adapter, 0x4550);
		*raw_4551 = rtw_read8(Adapter, 0x4551);
		*raw_4040 = rtw_read32(Adapter, 0x4040);
		for (i = 0; i < 9; i++)
			iqk_bb_backup[i] = rtw_read32(Adapter, iqk_bb_regs[i]);
	}

	/* ADDA On for Path A */
	rtw_write32(Adapter, 0x485c, 0xd0d8a405);
	for (i = 1; i < 16; i++)
		rtw_write32(Adapter, adda_regs[i], 0xd0dba405);

	if (t == 0)
		*pi_mode = (u8)s9082c_read_bbreg(Adapter, 0x4820, 0x100);

	if (!(*pi_mode)) {
		rtw_write32(Adapter, 0x4820, 0x80008000);
		rtw_write32(Adapter, 0x4828, 0x80008000);
	}

	/* MAC settings for calibration */
	rtw_write8(Adapter, 0x4522, 0xfc);
	rtw_write8(Adapter, 0x4550, (*raw_4550) & ~0x10);
	rtw_write8(Adapter, 0x4551, (*raw_4551) & ~0x10);
	rtw_write8(Adapter, 0x4040, (u8)((*raw_4040) & 0xff) & ~0x04);

	/* BB IQK common setup */
	s9082c_write_bbreg(Adapter, 0x4a04, 0x0f000000, 0xf);
	rtw_write32(Adapter, 0x4c04, 0xc0056a00);
	rtw_write32(Adapter, 0x4c08, 0x00100027);
	rtw_write32(Adapter, 0x4874, 0x44040200);
	s9082c_write_bbreg(Adapter, 0x4870, BIT(10), 1);
	s9082c_write_bbreg(Adapter, 0x4870, BIT(26), 1);
	s9082c_write_bbreg(Adapter, 0x4860, BIT(10), 0);
	s9082c_write_bbreg(Adapter, 0x4864, BIT(10), 0);
	rtw_write32(Adapter, 0x4b68, 0xf0060000);
	s9082c_write_bbreg(Adapter, 0x4e28, 0xffffff00, 0x00808000);
	rtw_write32(Adapter, 0x4e40, 0x80003e00);
	rtw_write32(Adapter, 0x4e44, 0x81001200);

	/* TX IQK */
	for (i = 0; i < retry; i++) {
		patha_ok = s9082c_path_a_tx_iqk(Adapter);
		if (patha_ok == 0x01) {
			result[t][0] = (s32)((rtw_read32(Adapter, 0x4e94) >> 16) & 0x3ff);
			result[t][1] = (s32)((s9082c_read_bbreg(Adapter, 0x4e9c, 0xffffffff) >> 16) & 0x3ff);
			break;
		}
	}

	/* RX IQK */
	for (i = 0; i < retry; i++) {
		patha_ok = s9082c_path_a_rx_iqk(Adapter);
		if (patha_ok == 0x03) {
			result[t][2] = (s32)((rtw_read32(Adapter, 0x4ea4) >> 16) & 0x3ff);
			result[t][3] = (s32)((rtw_read32(Adapter, 0x4eac) >> 16) & 0x3ff);
			break;
		}
	}

	/* IQK block off */
	s9082c_write_bbreg(Adapter, 0x4e28, 0xffffff00, 0);

	/* S9082C-FIX (Bug#6): RF 0xef (BIT19 = IQK/Testmodus) nach der IQK zurücksetzen,
	 * sonst bleibt der RF8353-Transceiver im Kalibriermodus (init setzt 0x000a0). */
	s9082c_write_rfreg(Adapter, RF_PATH_A, 0xef, 0xfffff, 0x000a0);

	if (t != 0) {
		if (!(*pi_mode)) {
			rtw_write32(Adapter, 0x4820, 0x80000000);
			rtw_write32(Adapter, 0x4828, 0x80000000);
		}
		for (i = 0; i < 16; i++)
			rtw_write32(Adapter, adda_regs[i], adda_backup[i]);
		rtw_write8(Adapter, 0x4522, *raw_4522);
		rtw_write8(Adapter, 0x4550, *raw_4550);
		rtw_write8(Adapter, 0x4551, *raw_4551);
		rtw_write32(Adapter, 0x4040, *raw_4040);
		for (i = 0; i < 9; i++)
			rtw_write32(Adapter, iqk_bb_regs[i], iqk_bb_backup[i]);
		rtw_write32(Adapter, 0x4840, 0x00c074cb);
		rtw_write32(Adapter, 0x4e30, 0x80003100);
		rtw_write32(Adapter, 0x4e34, 0x80003100);
	}
}

static bool s9082c_iqk_simularity(s32 result[][8], u8 c1, u8 c2)
{
	u32 i, j, diff, sim_bitmap = 0;
	u8 final_candidate = 0xff;

	for (i = 0; i < 4; i++) {
		diff = (result[c1][i] > result[c2][i]) ?
		       (result[c1][i] - result[c2][i]) :
		       (result[c2][i] - result[c1][i]);
		if (diff > 5) {
			if (i == 2 && !sim_bitmap) {
				if (result[c1][i] + result[c1][i + 1] == 0)
					final_candidate = c2;
				else if (result[c2][i] + result[c2][i + 1] == 0)
					final_candidate = c1;
				else
					sim_bitmap |= (1 << i);
			} else {
				sim_bitmap |= (1 << i);
			}
		}
	}

	if (sim_bitmap == 0) {
		if (final_candidate != 0xff) {
			for (j = 0; j < 2; j++)
				result[3][j] = result[final_candidate][j];
			return false;
		}
		return true;
	} else if (!(sim_bitmap & 0x0f)) {
		for (i = 0; i < 4; i++)
			result[3][i] = result[c1][i];
		return false;
	}

	return false;
}

void s9082c_iq_calibrate(PADAPTER Adapter)
{
	HAL_DATA_TYPE *pHalData = GET_HAL_DATA(Adapter);
	struct dm_struct *dm = &pHalData->odmpriv;
	s32 result[4][8];
	u32 adda_backup[16];
	u32 iqk_bb_backup[9];
	u32 raw_4040 = 0;
	u8 raw_4522 = 0, raw_4550 = 0, raw_4551 = 0, pi_mode = 0;
	u8 t, final_candidate = 0xff;
	s32 e94 = 0, e9c = 0, ea4 = 0, eac = 0, reg_tmp = 0;
	u8 idx;

	_rtw_memset(result, 0, sizeof(result));

	for (t = 0; t < 3; t++) {
		s9082c_iqk_single(Adapter, result, t, adda_backup, iqk_bb_backup,
				  &raw_4522, &raw_4550, &raw_4551, &raw_4040, &pi_mode);
		if (t == 1) {
			if (s9082c_iqk_simularity(result, 0, 1)) {
				final_candidate = 0;
				break;
			}
		} else if (t == 2) {
			if (s9082c_iqk_simularity(result, 0, 2)) {
				final_candidate = 0;
				break;
			} else if (s9082c_iqk_simularity(result, 1, 2)) {
				final_candidate = 1;
				break;
			} else {
				for (idx = 0; idx < 4; idx++)
					reg_tmp += result[3][idx];
				final_candidate = (reg_tmp != 0) ? 3 : 0xff;
			}
		}
	}

	if (final_candidate != 0xff) {
		e94 = result[final_candidate][0];
		e9c = result[final_candidate][1];
		ea4 = result[final_candidate][2];
		eac = result[final_candidate][3];
		dm->rf_calibrate_info.rege94 = e94;
		dm->rf_calibrate_info.rege9c = e9c;
	} else {
		dm->rf_calibrate_info.rege94 = 0x100;
		dm->rf_calibrate_info.rege9c = 0x0;
	}

	if (final_candidate != 0xff && result[final_candidate][0] != 0) {
		s32 x = result[final_candidate][0];
		s32 y = result[final_candidate][1];
		s32 oldval_0 = (s32)(rtw_read32(Adapter, 0x4c80) >> 22);
		s32 val_x, tx0_a, val_y, tx0_c;
		u32 c4c;

		if (x & 0x00000200)
			x |= 0xfffffc00;
		val_x = x * oldval_0;
		tx0_a = (val_x >> 8) & 0x3ff;
		s9082c_write_bbreg(Adapter, 0x4c80, 0x3ff, tx0_a);

		c4c = rtw_read32(Adapter, 0x4c4c);
		if ((val_x >> 7) & 0x1)
			c4c |= 0x01000000;
		else
			c4c &= ~0x01000000;

		if (y & 0x00000200)
			y |= 0xfffffc00;
		val_y = y * oldval_0;
		tx0_c = val_y >> 8;
		s9082c_write_bbreg(Adapter, 0x4c94, 0xf0000000, (tx0_c >> 6) & 0xf);
		s9082c_write_bbreg(Adapter, 0x4c80, 0x003f0000, tx0_c & 0x3f);

		if ((val_y >> 7) & 0x1)
			c4c |= 0x04000000;
		else
			c4c &= ~0x04000000;
		rtw_write32(Adapter, 0x4c4c, c4c);

		if (result[final_candidate][2] != 0) {
			u32 rx_x = result[final_candidate][2];
			u32 rx_y = result[final_candidate][3];
			s9082c_write_bbreg(Adapter, 0x4c14, 0x3ff, rx_x);
			s9082c_write_bbreg(Adapter, 0x4c14, 0xfc00, rx_y & 0x3f);
			s9082c_write_bbreg(Adapter, 0x4ca0, 0xf0000000, (rx_y >> 6) & 0xf);
		}
	}

	RTW_INFO("S9082C IQK done: cand=%u e94=0x%x e9c=0x%x ea4=0x%x eac=0x%x\n",
		 final_candidate, e94, e9c, ea4, eac);
}
